import type { IncidentType, IncidentPriority } from '@/types'

export interface IncidentContext {
  incidentType: IncidentType
  priority: IncidentPriority
  location: string
  description: string
}

export interface GeneratedAlert {
  english: string
  tagalog: string
}

const ENGLISH_PROMPT = (ctx: IncidentContext) => `
You are the official emergency communications officer for Barangay 178, Camarin, Caloocan City, Philippines.

Your task is to rewrite the following raw emergency incident description into a clear, concise, and highly actionable Emergency Alert Message for public broadcast. Do NOT summarize this like an essay.

Incident Details:
- Incident Type: ${ctx.incidentType}
- Priority Level: ${ctx.priority}
- Incident Location: ${ctx.location}
- Raw Incident Description: ${ctx.description}

Instructions for the Alert Message:
1. Identify the event type (e.g., Fire, Flood, Crime, Medical emergency).
2. State the immediate area/location clearly so residents know if they are affected.
3. Provide a clear, actionable directive for residents (e.g., evacuate, stay indoors, yield to emergency vehicles).
4. Keep it calm, authoritative, brief, and under 3 sentences.
5. Use extremely simple, clear, and direct English vocabulary. Do NOT use complex, deep, formal, or technical terms that might be difficult for a simple citizen to understand.
6. Write ONLY the final emergency broadcast message. Do not include any intros, notes, formatting prefixes, or conversational filler.

Emergency Alert Message:
`.trim()

