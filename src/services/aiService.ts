export function getActiveAiVersion(): 'v1' | 'v2' {
  if (typeof window !== 'undefined') {
    return (localStorage.getItem('barangay_ai_version') as 'v1' | 'v2') || 'v2'
  }
  return 'v2'
}

async function callChatGPT(prompt: string): Promise<string> {
  const response = await fetch('/api/openrouter', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      model: 'openai/gpt-3.5-turbo',
      messages: [
        {
          role: 'user',
          content: prompt,
        },
      ],
      temperature: 0.3,
      max_tokens: 300,
    }),
  })

  if (!response.ok) {
    const error = await response.text()
    throw new Error(`ChatGPT API error: ${response.status} — ${error}`)
  }

  const data = await response.json()
  const text = data?.choices?.[0]?.message?.content

  if (!text) {
    throw new Error('No response generated by ChatGPT.')
  }

  return text.trim()
}

async function callGemini(prompt: string): Promise<string> {
  // Try Gemini 2.0 Flash via OpenRouter (same pipeline as ChatGPT — identical request format)
  try {
    const response = await fetch('/api/openrouter', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: 'google/gemini-2.0-flash-001',
        messages: [{ role: 'user', content: prompt }],
        temperature: 0.3,
        max_tokens: 300,
      }),
    })
    if (response.ok) {
      const data = await response.json()
      const text = data?.choices?.[0]?.message?.content
      if (text && text.trim()) return text.trim()
    }
  } catch (_) { /* fall through */ }

  // Fallback: use ChatGPT via OpenRouter if Gemini model isn't available
  return callChatGPT(prompt)
}


export async function generateEnglishAlert(ctx: IncidentContext): Promise<string> {
  return callGemini(ENGLISH_PROMPT(ctx))
}

export async function generateTagalogAlert(ctx: IncidentContext): Promise<string> {
  return callGemini(TAGALOG_PROMPT(ctx))
}

export async function generateBothAlerts(ctx: IncidentContext): Promise<GeneratedAlert> {
  const [english, tagalog] = await Promise.all([
    generateEnglishAlert(ctx),
    generateTagalogAlert(ctx),
  ])
  return { english, tagalog }
}

export function isGeminiConfigured(): boolean {
  return true
}

export interface DetectionAndTranslation {
  detected_language: 'English' | 'Tagalog'
  translated_text: string
}

export async function detectAndTranslateIncident(description: string): Promise<DetectionAndTranslation> {
  if (!description || !description.trim()) {
    return { detected_language: 'English', translated_text: '' }
  }

  const prompt = `
You are a bilingual emergency communication processor. Detect if the input emergency log is in English or Tagalog. Translate it to the OPPOSITE language. Keep the tone accurate and clear for local barangay officials.

Input Emergency Log:
"${description.trim()}"

Output your response strictly in the following JSON format:
{
  "detected_language": "English or Tagalog",
  "translated_text": "Write the translated text here"
}

Do not write any markdown codeblock formatting, preamble, introductions, or conversational notes. Output only the raw JSON.
  `.trim()

  const responseText = await callGemini(prompt)
  try {
    const cleanText = responseText.replace(/```json/i, '').replace(/```/g, '').trim()
    const parsed = JSON.parse(cleanText)
    if (parsed.detected_language && parsed.translated_text) {
      return {
        detected_language: parsed.detected_language.includes('Tagalog') ? 'Tagalog' : 'English',
        translated_text: parsed.translated_text.trim(),
      }
    }
    throw new Error('Incomplete JSON response')
  } catch (err) {
    console.error('Failed to parse detect & translate JSON from Gemini:', err, responseText)
    const containsTagalog = /[ng\s]mga|[sa\s]tulong|nasunog|baha|insidente|sakolo|sunog/i.test(description)
    return {
      detected_language: containsTagalog ? 'Tagalog' : 'English',
      translated_text: description,
    }
  }
}
